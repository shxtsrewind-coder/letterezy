# Halves of contractions ("don't" → don) are real ENABLE words but read as typos in a hint.
CONTRACTION_GHOSTS = set("don isn doesn didn wasn aren couldn wouldn shouldn hadn hasn haven weren mustn needn ain cant dont wont ive ill".split())
common = [w for w in enable if w in popular and w in rank and rank[w] < 30000 and w not in BLOCK and w not in CONTRACTION_GHOSTS]
common.sort(key=lambda w: rank[w])

out = (
    "// Generated by scripts/build_words.py — don't edit by hand.\n"
    "// VALID: every ENABLE word of 3–7 letters (public domain word list).\n"
    "// COMMON: everyday words, most frequent first, for hints and daily-bag checks.\n"
    f"export const VALID_WORDS = \"{' '.join(enable)}\";\n"
    f"export const COMMON_WORDS = \"{' '.join(common)}\";\n"
)
OUT.write_text(out)
print(f"VALID {len(enable)} words, COMMON {len(common)} words, {len(out) // 1024} KB")
